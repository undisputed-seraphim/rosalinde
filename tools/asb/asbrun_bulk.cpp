int scan(const cpk::archive& archive, const ScanOptions& options) {
	if ((options.scene || options.scene_index || options.scene_ir) && options.json_path.empty()) {
		std::cerr << "scan: --scene/--scene-index/--scene-ir require --json\n";
		return 2;
	}

	asb::CharTable chars;
	if (!options.chara_file.empty())
		chars = asb::load_char_table(options.chara_file);
	else if (options.scene_ir) {
		const auto chara_path = std::filesystem::path(rosalinde_data_dir()) / "chara_table.tsv";
		if (std::filesystem::exists(chara_path))
			chars = asb::load_char_table(chara_path.string());
	}

	std::ofstream json_file;
	std::ostream* json_out = nullptr;
	if (!options.json_path.empty()) {
		if (options.json_path != "-") {
			json_file = open_output(options.json_path);
			json_out = &json_file;
		} else {
			json_out = &std::cout;
		}
		*json_out << "[\n";
	}

	const std::vector<std::string> entries = script_entries(archive, options.filter);
	size_t processed = 0;
	bool first = true;
	for (const auto& path : entries) {
		if (options.limit > 0 && processed >= options.limit)
			break;

		const std::vector<uint8_t> bytes = extract_entry(archive, path);
		const asb::Module module = asb::parse(std::span<const uint8_t>(bytes.data(), bytes.size()));

		if (json_out) {
			*json_out << (first ? "" : ",\n")
					  << module_object(module, path, bytes.size(), options, chars.empty() ? nullptr : &chars);
			first = false;
		} else {
			std::cout << module_text_summary(module, path);
		}
		++processed;

		if (options.disasm_dir.empty() && !options.disasm)
			continue;
		std::string disassembly;
		for (const auto& function : module.functions)
			disassembly += asb::disassemble(module, *function) + "\n";
		if (!options.disasm_dir.empty()) {
			std::filesystem::create_directories(options.disasm_dir);
			const std::filesystem::path out_path =
				std::filesystem::path(options.disasm_dir) / (std::filesystem::path(path).filename().string() + ".txt");
			std::ofstream out(out_path, std::ios::binary | std::ios::trunc);
			if (!out)
				throw std::runtime_error("cannot write " + out_path.string());
			out << disassembly;
		} else {
			std::cout << disassembly;
		}
	}

	if (json_out)
		*json_out << "\n]\n";
	return 0;
}

int export_chara(const cpk::archive& archive, const std::string& out_path) {
	std::map<std::string, asb::CharaInfo> table;
	for (const auto& path : script_entries(archive, {})) {
		const std::vector<uint8_t> bytes = extract_entry(archive, path);
		const asb::Module module = asb::parse(std::span<const uint8_t>(bytes.data(), bytes.size()));
		accumulate_chara(module, table);
	}
	std::ostringstream out;
	write_chara_table(table, out);
	write_text_output(out_path, out.str());
	return 0;
}

int export_enums(const cpk::archive& archive, const std::string& out_path) {
	std::ostringstream out;
	out << "# kind\tname\tcomment (generated from Debug/_UcEnum_*.inc by asbrun export enums)\n";
	const char* files[] = {
		"_UcEnum_Class.inc",
		"_UcEnum_CharaSet.inc",
		"_UcEnum_CharaNpc.inc",
		"_UcEnum_Facility.inc",
		"_UcEnum_Item.inc",
		"_UcEnum_DropTable.inc"};
	for (const char* file : files) {
		std::vector<char> buffer;
		archive.extract("Debug", file, buffer);
		parse_uc_enum(std::string(buffer.begin(), buffer.end()), out);
	}
	write_text_output(out_path, out.str());
	return 0;
}

int export_bgs(const cpk::archive& archive, const std::string& out_path) {
	std::set<std::string> files;
	for (const auto& item : archive) {
		if (item.dir == "BattleBG")
			files.insert(std::string(item.name));
	}
	std::ostringstream out;
	out << "# key\tmbs\tftx (generated from BattleBG/* by asbrun export bgs)\n";
	for (const auto& file : files) {
		if (!ends_with(file, ".mbs"))
			continue;
		const std::string stem = file.substr(0, file.size() - 4);
		const std::string ftx = stem + ".ftx";
		out << stem << '\t' << file << '\t' << (files.contains(ftx) ? ftx : std::string()) << '\n';
	}
	write_text_output(out_path, out.str());
	return 0;
}

