std::vector<std::string> script_entries(const cpk::archive& archive, std::string_view filter) {
	const std::string needle = lower(std::string(filter));
	std::vector<std::string> entries;
	for (const auto& item : archive) {
		if (item.dir != "Script")
			continue;
		std::string name(item.name);
		if (!ends_with(name, ".asb"))
			continue;
		const std::string path = "Script/" + name;
		if (!needle.empty() && lower(path).find(needle) == std::string::npos)
			continue;
		entries.push_back(std::move(path));
	}
	std::sort(entries.begin(), entries.end());
	return entries;
}

std::ofstream open_output(const std::string& path) {
	const std::filesystem::path parent = std::filesystem::path(path).parent_path();
	if (!parent.empty())
		std::filesystem::create_directories(parent);
	std::ofstream file(path, std::ios::trunc | std::ios::binary);
	if (!file)
		throw std::runtime_error("cannot write " + path);
	return file;
}

void write_text_output(const std::string& path, const std::string& text) {
	std::ostream* out = &std::cout;
	std::ofstream file;
	if (path != "-" && !path.empty()) {
		file = open_output(path);
		out = &file;
	}
	*out << text;
}

void accumulate_chara(const asb::Module& module, std::map<std::string, asb::CharaInfo>& out) {
	const asb::Scene scene = asb::extract_scene(module);
	for (const auto& function : scene.functions) {
		for (const auto& event : function.events) {
			if (event.call == "DrUiCreateChara" && event.strings.size() >= 4) {
				asb::CharaInfo info;
				info.ftx = event.strings[0];
				info.mbs = event.strings[1];
				info.disp_name = event.strings[2];
				out.emplace(event.strings[3], std::move(info));
			}
		}
	}
}

void write_chara_table(const std::map<std::string, asb::CharaInfo>& table, std::ostream& out) {
	out << "# character name -> display name, mbs, ftx (generated by asbrun export chara)\n";
	for (const auto& [name, info] : table)
		out << name << '\t' << info.disp_name << '\t' << info.mbs << '\t' << info.ftx << '\n';
}

void parse_uc_enum(const std::string& content, std::ostream& out) {
	std::istringstream input(content);
	std::string line;
	std::string table;
	while (std::getline(input, line)) {
		const auto comma = line.find(',');
		if (comma == std::string::npos) {
			const auto colon = line.find(':');
			if (colon != std::string::npos) {
				table.clear();
				for (char c : line.substr(0, colon)) {
					if (std::isalnum(static_cast<unsigned char>(c)) || c == '_')
						table += c;
				}
			}
			continue;
		}
		if (table.empty())
			continue;
		const std::string name = std::string(trim(line.substr(0, comma)));
		std::string comment;
		const auto comment_at = line.find("//");
		if (comment_at != std::string::npos)
			comment = std::string(trim(line.substr(comment_at + 2)));
		if (!name.empty())
			out << table << '\t' << name << '\t' << comment << '\n';
	}
}

std::string module_text_summary(const asb::Module& module, std::string_view path) {
	size_t natives = 0;
	for (size_t i = 0; i < module.used_functions.size(); ++i) {
		if (i < module.used_function_kind.size() && module.used_function_kind[i] == 'a' && module.used_functions[i])
			++natives;
	}
	std::set<std::string> sections;
	for (const auto& function : module.functions) {
		if (!function->script_section.empty())
			sections.insert(function->script_section);
	}
	size_t assets = 0;
	for (const auto& text : module.used_strings) {
		if (is_asset(text))
			++assets;
	}
	std::ostringstream out;
	out << path << " parse=" << (module.error.empty() && module.consumed == module.total ? "OK" : "FAIL")
		<< " funcs=" << module.functions.size() << " natives=" << natives << " assets=" << assets
		<< " sections=" << sections.size() << '\n';
	return out.str();
}

std::string module_object(
	const asb::Module& module,
	std::string_view path,
	size_t size,
	const ScanOptions& options,
	const asb::CharTable* chars) {
	if (options.scene)
		return scene_json(module, std::string(path));
	if (options.scene_index)
		return scene_index_json(module, std::string(path));
	if (options.scene_ir)
		return scene_ir_json(module, std::string(path), chars);
	return harvest_json(module, std::string(path), size, options.summary);
}

